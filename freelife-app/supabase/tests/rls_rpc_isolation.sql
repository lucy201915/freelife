CREATE TEMP TABLE _fl_test (
  ord int GENERATED BY DEFAULT AS IDENTITY,
  step text,
  ok boolean,
  detail text
);
GRANT ALL ON TABLE _fl_test TO anon, authenticated;

DO $test$
DECLARE
  oid uuid;
  o public.orders%ROWTYPE;
  n int;
  j jsonb;
  r uuid;
  d uuid;
BEGIN
  -- Anon catalog access
  PERFORM set_config('request.jwt.claims', '', true);
  PERFORM set_config('request.jwt.claim.sub', '', true);
  EXECUTE 'SET LOCAL ROLE anon';

  SELECT count(*) INTO n FROM public.profiles;
  INSERT INTO _fl_test (step, ok, detail) VALUES ('anon_select_profiles', n >= 9, 'profiles visible=' || n);

  SELECT count(*) INTO n FROM public.services WHERE status = 'active';
  INSERT INTO _fl_test (step, ok, detail) VALUES ('anon_select_active_services', n = 5, 'services=' || n);

  SELECT count(*) INTO n FROM public.list_public_services('', '');
  INSERT INTO _fl_test (step, ok, detail) VALUES ('anon_list_public_services', n = 5, 'rpc=' || n);

  j := public.get_public_service_page('brand-community-audit');
  INSERT INTO _fl_test (step, ok, detail) VALUES (
    'anon_get_public_service_page',
    (j -> 'service' ->> 'slug') = 'brand-community-audit' AND (j -> 'talent' ->> 'name') IS NOT NULL,
    coalesce(j -> 'talent' ->> 'name', 'null')
  );

  BEGIN
    INSERT INTO public.orders (business_id, talent_id, service_id, package_id, package_tier, price, delivery_days, brief)
    VALUES (
      '11111111-1111-4111-8111-111111111111',
      '22222222-2222-4222-8222-222222222201',
      'a0000000-0000-4000-8000-000000000001',
      'b0000000-0000-4000-8000-000000000012',
      'standard', 1, 10, '[TEST-FREELIFE-APP] should not insert'
    );
    INSERT INTO _fl_test (step, ok, detail) VALUES ('anon_cannot_insert_order', false, 'insert unexpectedly succeeded');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('anon_cannot_insert_order', true, SQLERRM);
  END;

  EXECUTE 'RESET ROLE';

  -- Talent cannot create_order
  PERFORM set_config('request.jwt.claim.sub', '22222222-2222-4222-8222-222222222201', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','22222222-2222-4222-8222-222222222201','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';
  BEGIN
    oid := public.create_order('a0000000-0000-4000-8000-000000000001', 'standard', '[TEST-FREELIFE-APP] talent should fail');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_cannot_create_order', false, 'create_order unexpectedly succeeded id=' || oid);
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_cannot_create_order', true, SQLERRM);
  END;
  EXECUTE 'RESET ROLE';

  -- Business creates order; price snapshotted
  PERFORM set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111111', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','11111111-1111-4111-8111-111111111111','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';

  BEGIN
    oid := public.create_order('a0000000-0000-4000-8000-000000000001', 'gold', '[TEST-FREELIFE-APP] bad tier');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('invalid_tier_rejected', false, 'gold tier accepted');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('invalid_tier_rejected', true, SQLERRM);
  END;

  oid := public.create_order('a0000000-0000-4000-8000-000000000001', 'standard', '[TEST-FREELIFE-APP] rls price snapshot');
  SELECT * INTO o FROM public.orders WHERE id = oid;
  INSERT INTO _fl_test (step, ok, detail) VALUES (
    'business_create_order_price_snapshot',
    o.price = 12800 AND o.delivery_days = 10 AND o.revisions = 2 AND o.status = 'pending' AND o.package_tier = 'standard',
    'id=' || o.id || ' price=' || o.price || ' days=' || o.delivery_days || ' rev=' || o.revisions || ' status=' || o.status
  );

  BEGIN
    UPDATE public.orders SET price = 1, status = 'completed' WHERE id = oid;
    SELECT * INTO o FROM public.orders WHERE id = oid;
    INSERT INTO _fl_test (step, ok, detail) VALUES (
      'direct_price_status_update_denied',
      o.price = 12800 AND o.status = 'pending',
      'price=' || o.price || ' status=' || o.status
    );
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('direct_price_status_update_denied', true, SQLERRM);
  END;
  EXECUTE 'RESET ROLE';

  -- Other business isolation
  PERFORM set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111112', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','11111111-1111-4111-8111-111111111112','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';
  SELECT count(*) INTO n FROM public.orders WHERE brief = '[TEST-FREELIFE-APP] rls price snapshot';
  INSERT INTO _fl_test (step, ok, detail) VALUES ('other_business_cannot_see_order', n = 0, 'visible=' || n);
  BEGIN
    PERFORM public.update_order_status(oid, 'accepted');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('other_business_cannot_accept', false, 'accept succeeded');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('other_business_cannot_accept', true, SQLERRM);
  END;
  EXECUTE 'RESET ROLE';

  -- Talent flow
  PERFORM set_config('request.jwt.claim.sub', '22222222-2222-4222-8222-222222222201', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','22222222-2222-4222-8222-222222222201','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';
  o := public.update_order_status(oid, 'accepted');
  INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_accepts_order', o.status = 'accepted', o.status);
  BEGIN
    PERFORM public.update_order_status(oid, 'completed');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_cannot_complete', false, 'completed unexpectedly');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_cannot_complete', true, SQLERRM);
  END;
  d := public.submit_order_delivery(oid, '[TEST-FREELIFE-APP] delivery notes', '[]'::jsonb);
  INSERT INTO _fl_test (step, ok, detail) VALUES ('talent_submit_delivery', d IS NOT NULL, 'delivery=' || d::text);
  EXECUTE 'RESET ROLE';

  -- Business completes + reviews
  PERFORM set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111111', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','11111111-1111-4111-8111-111111111111','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';
  BEGIN
    PERFORM public.create_service_review(oid, 5, '[TEST-FREELIFE-APP] too early');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('review_before_complete_rejected', false, 'review accepted too early');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('review_before_complete_rejected', true, SQLERRM);
  END;
  o := public.update_order_status(oid, 'completed');
  INSERT INTO _fl_test (step, ok, detail) VALUES ('business_completes_order', o.status = 'completed', o.status);
  r := public.create_service_review(oid, 5, '[TEST-FREELIFE-APP] great work');
  INSERT INTO _fl_test (step, ok, detail) VALUES ('buyer_creates_review', r IS NOT NULL, 'review=' || r::text);
  BEGIN
    PERFORM public.create_service_review(oid, 4, '[TEST-FREELIFE-APP] duplicate');
    INSERT INTO _fl_test (step, ok, detail) VALUES ('duplicate_review_rejected', false, 'duplicate accepted');
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO _fl_test (step, ok, detail) VALUES ('duplicate_review_rejected', true, SQLERRM);
  END;

  INSERT INTO public.service_favorites (user_id, service_id)
  VALUES ('11111111-1111-4111-8111-111111111111', 'a0000000-0000-4000-8000-000000000001')
  ON CONFLICT DO NOTHING;
  SELECT count(*) INTO n FROM public.service_favorites WHERE service_id = 'a0000000-0000-4000-8000-000000000001';
  INSERT INTO _fl_test (step, ok, detail) VALUES ('owner_sees_service_favorite', n = 1, 'favs=' || n);

  j := public.start_service_contact('a0000000-0000-4000-8000-000000000001', 'quote', '[TEST-FREELIFE-APP] contact note');
  INSERT INTO _fl_test (step, ok, detail) VALUES (
    'start_service_contact',
    (j ? 'invite_id') AND (j ? 'conversation_id'),
    j::text
  );
  EXECUTE 'RESET ROLE';

  -- Other business cannot see favorite
  PERFORM set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111112', true);
  PERFORM set_config('request.jwt.claim.role', 'authenticated', true);
  PERFORM set_config('request.jwt.claims', json_build_object('sub','11111111-1111-4111-8111-111111111112','role','authenticated')::text, true);
  EXECUTE 'SET LOCAL ROLE authenticated';
  SELECT count(*) INTO n FROM public.service_favorites WHERE service_id = 'a0000000-0000-4000-8000-000000000001';
  INSERT INTO _fl_test (step, ok, detail) VALUES ('other_business_cannot_see_favorite', n = 0, 'favs=' || n);
  EXECUTE 'RESET ROLE';
END;
$test$;

-- Cleanup test artifacts
DELETE FROM public.service_reviews WHERE comment LIKE '[TEST-FREELIFE-APP]%';
DELETE FROM public.order_deliveries WHERE message LIKE '[TEST-FREELIFE-APP]%';
DELETE FROM public.orders WHERE brief LIKE '[TEST-FREELIFE-APP]%';
DELETE FROM public.service_favorites
 WHERE user_id = '11111111-1111-4111-8111-111111111111'
   AND service_id = 'a0000000-0000-4000-8000-000000000001';
DELETE FROM public.invites WHERE note LIKE '[TEST-FREELIFE-APP]%';

SELECT step, ok, detail FROM _fl_test ORDER BY ord;
